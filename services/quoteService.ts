type QuoteParser = (data: unknown) => InspirationContent | null;

interface QuoteSource {
  name: string;
  url: string;
  parse: QuoteParser;
}

let lastFallbackIndex = -1;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

function getNonEmptyString(value: unknown): string | null {
  return typeof value === 'string' && value.trim() ? value.trim() : null;
}

function getVerseTranslation(verse: Record<string, unknown>): string | null {
  if (!Array.isArray(verse.translations) || !isRecord(verse.translations[0])) {
    return null;
  }

  return getNonEmptyString(verse.translations[0].text);
}

function parseIslamicApp(data: unknown): InspirationContent | null {
  if (!isRecord(data) || !isRecord(data.data) || !isRecord(data.data.verse)) {
    return null;
  }

  const verse = data.data.verse;
  const quote = getVerseTranslation(verse);
  const verseKey = getNonEmptyString(verse.verse_key);

  if (!quote || !verseKey) {
    return null;
  }

  return {
    quote,
    source: `QS. ${verseKey} — Terjemahan Kemenag`,
  };
}

function parseQuranCom(data: unknown): InspirationContent | null {
  if (!isRecord(data) || !isRecord(data.verse)) {
    return null;
  }

  const verse = data.verse;
  const quote = getVerseTranslation(verse);
  const verseKey = getNonEmptyString(verse.verse_key);

  if (!quote || !verseKey) {
    return null;
  }

  return {
    quote,
    source: `QS. ${verseKey} — Terjemahan Kemenag`,
  };
}

function parseAlquranCloud(data: unknown): InspirationContent | null {
  if (!isRecord(data) || !isRecord(data.data) || !isRecord(data.data.surah)) {
    return null;
  }

  const verse = data.data;
  const quote = getNonEmptyString(verse.text);
  const surah = verse.surah;
  if (!isRecord(surah)) {
    return null;
  }

  const englishName = getNonEmptyString(surah.englishName);
  const numberInSurah = verse.numberInSurah;

  if (!quote || !englishName || typeof numberInSurah !== 'number' || !Number.isFinite(numberInSurah)) {
    return null;
  }

  return {
    quote,
    source: `QS. ${englishName}: ${numberInSurah} — Terjemahan Kemenag`,
  };
}

async function fetchJson(url: string): Promise<unknown> {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 4000);

  try {
    const response = await fetch(url, { signal: controller.signal });

    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }

    return await response.json();
  } finally {
    // Timer harus dibersihkan untuk respons sukses maupun semua jenis kegagalan.
    clearTimeout(timeoutId);
  }
}

async function tryQuoteSource(source: QuoteSource): Promise<InspirationContent | null> {
  try {
    const data = await fetchJson(source.url);
    const quote = source.parse(data);

    if (!quote) {
      throw new Error('format respons tidak valid');
    }

    return quote;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.warn(`[Quote] ${source.name} gagal: ${message}`);
    return null;
  }
}

