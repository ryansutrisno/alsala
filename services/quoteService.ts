function getRandomFallback(): InspirationContent {
  let randomIndex = Math.floor(Math.random() * fallbackQuotes.length);

  if (fallbackQuotes.length > 1 && randomIndex === lastFallbackIndex) {
    randomIndex = (randomIndex + 1) % fallbackQuotes.length;
  }

  lastFallbackIndex = randomIndex;
  return fallbackQuotes[randomIndex];
}

